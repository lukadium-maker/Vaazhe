    private static func masking(_ form: String, in sentence: String) -> (blank: String, answer: String)? {
        let pattern = "(?<![A-Za-z'-])" + NSRegularExpression.escapedPattern(for: form) + "(?![A-Za-z'-])"
        guard let expression = try? NSRegularExpression(pattern: pattern, options: .caseInsensitive) else { return nil }
        let matches = expression.matches(in: sentence, range: NSRange(sentence.startIndex..., in: sentence))
        guard matches.count == 1, let match = matches.first, let range = Range(match.range, in: sentence) else { return nil }
        let answer = String(sentence[range])
        return (sentence.replacingCharacters(in: range, with: "_____"), answer)
    }

    static func blank(for card: Card) -> String? {
        if let entry = entries[card.id], entry.sentence == card.exampleEn {
            return masking(entry.form, in: card.exampleEn)?.blank
        }
        guard !card.word.isEmpty else { return nil }
        return masking(card.word, in: card.exampleEn)?.blank
    }

    static func question(for card: Card, using random: inout some RandomNumberGenerator) -> PracticeQuestion? {
        guard let entry = entries[card.id], card.exampleEn == entry.sentence,
              let prompt = masking(entry.form, in: entry.sentence) else { return nil }
        var options = entry.distractors + [entry.form]
        guard Set(options.map { $0.lowercased() }).count == 4 else { return nil }
        if prompt.answer.first?.isUppercase == true {
            options = options.map { $0.prefix(1).uppercased() + $0.dropFirst() }
        }
        return PracticeQuestion(card: card, blank: prompt.blank, answer: prompt.answer,
                                options: options.shuffled(using: &random))
    }
